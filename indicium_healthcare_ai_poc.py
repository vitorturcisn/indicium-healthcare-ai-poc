def preparar_banco_dados(path_2025, path_2026, path_db):
    """Lê os CSVs, limpa os dados sensíveis/ruídos e cria o banco SQLite."""
    print("[*] Iniciando pré-processamento estrito de dados...")

    df_2025 = pd.read_csv(path_2025, sep=';', low_memory=False)
    df_2026 = pd.read_csv(path_2026, sep=';', low_memory=False)
    df_bruto = pd.concat([df_2025, df_2026], ignore_index=True)

    colunas_alvo = [
        'DT_NOTIFIC', 'DT_SIN_PRI', 'SG_UF_NOT', 'ID_MUNICIP',
        'NU_IDADE_N', 'CS_SEXO', 'UTI', 'EVOLUCAO',
        'VACINA_COV', 'CLASSI_FIN'
    ]
    df_clean = df_bruto[colunas_alvo].copy()

    # Padronização de datas
    df_clean['DT_NOTIFIC'] = pd.to_datetime(df_clean['DT_NOTIFIC']).dt.tz_localize(None).dt.date
    df_clean['DT_SIN_PRI'] = pd.to_datetime(df_clean['DT_SIN_PRI']).dt.tz_localize(None).dt.date

    # Limpeza clínica (Removendo NaNs, códigos 9 e óbitos por outras causas)
    df_clean.dropna(subset=['UTI', 'EVOLUCAO', 'VACINA_COV'], inplace=True)
    df_clean = df_clean[df_clean['UTI'].isin([1.0, 2.0])]
    df_clean = df_clean[df_clean['EVOLUCAO'].isin([1.0, 2.0])]
    df_clean = df_clean[df_clean['VACINA_COV'].isin([1.0, 2.0])]

    # Tratamento da Classificação Final (4.0 = SRAG não especificada)
    df_clean['CLASSI_FIN'] = df_clean['CLASSI_FIN'].fillna(4.0)

    # Exportação
    with sqlite3.connect(path_db) as conexao:
        df_clean.to_sql('internacoes', conexao, if_exists='replace', index=False)

    print(f"[*] Banco de dados estruturado gerado com sucesso. Registros válidos: {df_clean.shape[0]}")

