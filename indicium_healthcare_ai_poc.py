@tool
def consultar_metricas() -> dict:
    """Consulta o banco SQLite para calcular UTI, mortalidade, vacinação e taxa de aumento."""
    with sqlite3.connect('/content/srag_dados.db') as conexao:
        query_geral = '''
        SELECT
            COUNT(*) as total,
            SUM(CASE WHEN UTI = 1.0 THEN 1 ELSE 0 END) as uti_casos,
            SUM(CASE WHEN EVOLUCAO = 2.0 THEN 1 ELSE 0 END) as obitos,
            SUM(CASE WHEN VACINA_COV = 1.0 THEN 1 ELSE 0 END) as vacinados
        FROM internacoes
        '''
        df_geral = pd.read_sql(query_geral, conexao)
        total = int(df_geral['total'].iloc[0])

        df_datas = pd.read_sql('SELECT MAX(DT_NOTIFIC) as max_data FROM internacoes', conexao)
        data_max = pd.to_datetime(df_datas['max_data'].iloc[0])

        data_30d = (data_max - timedelta(days=30)).strftime('%Y-%m-%d')
        data_60d = (data_max - timedelta(days=60)).strftime('%Y-%m-%d')
        data_max_str = data_max.strftime('%Y-%m-%d')

        query_recentes = f"SELECT COUNT(*) as casos FROM internacoes WHERE DT_NOTIFIC BETWEEN '{data_30d}' AND '{data_max_str}'"
        query_anteriores = f"SELECT COUNT(*) as casos FROM internacoes WHERE DT_NOTIFIC BETWEEN '{data_60d}' AND '{data_30d}'"

        casos_30d = pd.read_sql(query_recentes, conexao)['casos'].iloc[0]
        casos_60d = pd.read_sql(query_anteriores, conexao)['casos'].iloc[0]
        taxa_aumento = ((casos_30d - casos_60d) / casos_60d) * 100 if casos_60d > 0 else 0

    return {
        "taxa_ocupacao_uti": f"{(df_geral['uti_casos'].iloc[0] / total) * 100:.1f}%",
        "taxa_mortalidade": f"{(df_geral['obitos'].iloc[0] / total) * 100:.1f}%",
        "taxa_vacinacao": f"{(df_geral['vacinados'].iloc[0] / total) * 100:.1f}%",
        "taxa_aumento_casos_30d": f"{taxa_aumento:.1f}%",
        "casos_recentes_30d": int(casos_30d)
    }

@tool
def gerar_graficos() -> str:
    """Gera gráficos de casos de SRAG dos últimos 30 dias e 12 meses."""
    with sqlite3.connect('/content/srag_dados.db') as conexao:
        df = pd.read_sql('SELECT DT_NOTIFIC FROM internacoes', conexao)

    df['DT_NOTIFIC'] = pd.to_datetime(df['DT_NOTIFIC'])
    data_max = df['DT_NOTIFIC'].max()

    # Gráfico 1: 30 dias
    df_30d = df[df['DT_NOTIFIC'] > (data_max - timedelta(days=30))]
    plt.figure(figsize=(10, 5))
    df_30d.groupby('DT_NOTIFIC').size().plot(kind='line', color='red', marker='o')
    plt.title('Casos de SRAG - Últimos 30 Dias')
    plt.ylabel('Número de Casos')
    plt.grid(True)
    plt.savefig('/content/grafico_30_dias.png')
    plt.close()

    # Gráfico 2: 12 meses
    df_12m = df[df['DT_NOTIFIC'] > (data_max - timedelta(days=365))].copy()
    df_12m['Mes_Ano'] = df_12m['DT_NOTIFIC'].dt.to_period('M')
    plt.figure(figsize=(10, 5))
    df_12m.groupby('Mes_Ano').size().plot(kind='bar', color='blue')
    plt.title('Casos de SRAG - Últimos 12 Meses')
    plt.ylabel('Número de Casos')
    plt.xticks(rotation=45)
    plt.tight_layout()
    plt.savefig('/content/grafico_12_meses.png')
    plt.close()

    return "Gráficos 'grafico_30_dias.png' e 'grafico_12_meses.png' gerados com sucesso."

@tool
def buscar_noticias(query: str) -> str:
    """Busca notícias recentes na web para contextualização."""
    try:
        ddgs = DDGS()
        resultados = list(ddgs.text(query, region='br-tz', timelimit='m', max_results=3))
        contexto = "\n\n".join([f"Título: {r['title']}\nResumo: {r['body']}" for r in resultados])
        return contexto if contexto else "Nenhuma notícia relevante encontrada."
    except Exception as e:
        return f"Erro ao buscar notícias: {e}"

