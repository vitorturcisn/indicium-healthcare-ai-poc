def construir_grafo(llm_instance, tools_list):
    """Constrói e compila o fluxo do agente LangGraph."""
    llm_with_tools = llm_instance.bind_tools(tools_list)

    def agent_node(state: MessagesState):
        mensagens = state["messages"]
        if not any(isinstance(m, SystemMessage) for m in mensagens):
            sys_prompt = '''Você é um analista de dados de saúde sênior responsável por relatórios de SRAG.
            Siga rigorosamente estes passos:
            1. Chame 'consultar_metricas'.
            2. Chame 'gerar_graficos'.
            3. Chame 'buscar_noticias' com a query "Síndrome Respiratória Aguda Grave Brasil".
            4. Redija o relatório final estruturado contendo as métricas, análise contextual e confirmação visual.
            Mantenha um tom executivo, claro e direto.'''
            mensagens = [SystemMessage(content=sys_prompt)] + mensagens
        return {"messages": [llm_with_tools.invoke(mensagens)]}

    def should_continue(state: MessagesState):
        return "tools" if state["messages"][-1].tool_calls else END

    workflow = StateGraph(MessagesState)
    workflow.add_node("agent", agent_node)
    workflow.add_node("tools", ToolNode(tools_list))
    workflow.add_edge(START, "agent")
    workflow.add_conditional_edges("agent", should_continue, ["tools", END])
    workflow.add_edge("tools", "agent")

    return workflow.compile()

