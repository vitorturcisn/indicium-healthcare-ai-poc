@tool
def consultar_metricas() -> dict:
    """Calcula deterministicamente métricas epidemiológicas isolando o LLM do banco de dados."""
    with sqlite3.connect('/content/srag_dados.db') as conexao:
        df_geral = pd.read_sql('''
        SELECT COUNT(*) as total,
               SUM(CASE WHEN UTI = 1.0 THEN 1 ELSE 0 END) as uti_casos,
               SUM(CASE WHEN EVOLUCAO = 2.0 THEN 1 ELSE 0 END) as obitos,
               SUM(CASE WHEN VACINA_COV = 1.0 THEN 1 ELSE 0 END) as vacinados
        FROM internacoes''', conexao)

        total = int(df_geral['total'].iloc[0])
        data_max = pd.to_datetime(pd.read_sql('SELECT MAX(DT_NOTIFIC) as max_data FROM internacoes', conexao)['max_data'].iloc[0])

        d30 = (data_max - timedelta(days=30)).strftime('%Y-%m-%d')
        d60 = (data_max - timedelta(days=60)).strftime('%Y-%m-%d')
        dmax = data_max.strftime('%Y-%m-%d')

        c30 = pd.read_sql(f"SELECT COUNT(*) as c FROM internacoes WHERE DT_NOTIFIC BETWEEN '{d30}' AND '{dmax}'", conexao)['c'].iloc[0]
        c60 = pd.read_sql(f"SELECT COUNT(*) as c FROM internacoes WHERE DT_NOTIFIC BETWEEN '{d60}' AND '{d30}'", conexao)['c'].iloc[0]
        taxa_aumento = ((c30 - c60) / c60) * 100 if c60 > 0 else 0

    return {
        "taxa_internacao_uti": f"{(df_geral['uti_casos'].iloc[0] / total) * 100:.1f}%",
        "taxa_mortalidade_casos_fechados": f"{(df_geral['obitos'].iloc[0] / total) * 100:.1f}%",
        "proporcao_casos_vacinados": f"{(df_geral['vacinados'].iloc[0] / total) * 100:.1f}%",
        "variacao_casos_30d": f"{taxa_aumento:.1f}%",
        "volume_casos_recentes_30d": int(c30)
    }

@tool
def gerar_graficos() -> str:
    """Gera gráficos estáticos de suporte visual."""
    with sqlite3.connect('/content/srag_dados.db') as conexao:
        df = pd.read_sql('SELECT DT_NOTIFIC FROM internacoes', conexao)
    df['DT_NOTIFIC'] = pd.to_datetime(df['DT_NOTIFIC'])
    data_max = df['DT_NOTIFIC'].max()

    df_30d = df[df['DT_NOTIFIC'] > (data_max - timedelta(days=30))]
    plt.figure(figsize=(10, 5))
    df_30d.groupby('DT_NOTIFIC').size().plot(kind='line', color='red', marker='o')
    plt.title('Incidência de SRAG - Últimos 30 Dias')
    plt.grid(True)
    plt.savefig('/content/grafico_30_dias.png')
    plt.close()

    df_12m = df[df['DT_NOTIFIC'] > (data_max - timedelta(days=365))].copy()
    df_12m['Mes_Ano'] = df_12m['DT_NOTIFIC'].dt.to_period('M')
    plt.figure(figsize=(10, 5))
    df_12m.groupby('Mes_Ano').size().plot(kind='bar', color='blue')
    plt.title('Incidência de SRAG - Histórico 12 Meses')
    plt.xticks(rotation=45)
    plt.tight_layout()
    plt.savefig('/content/grafico_12_meses.png')
    plt.close()
    return "Gráficos 'grafico_30_dias.png' e 'grafico_12_meses.png' gerados."

@tool
def buscar_noticias(query: str) -> str:
    """Busca contexto apenas em fontes confiáveis."""
    try:
        ddgs = DDGS()
        resultados = list(ddgs.text(query + " site:gov.br OR site:fiocruz.br OR site:who.int", region='br-tz', timelimit='m', max_results=3))
        return "\n\n".join([f"Título: {r['title']}\nResumo: {r['body']}" for r in resultados]) if resultados else "Nenhum alerta recente encontrado em fontes oficiais."
    except Exception as e:
        return f"Falha na busca contextual: {e}"

